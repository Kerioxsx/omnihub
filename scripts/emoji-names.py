#!/usr/bin/env python3
"""Rebuild src/desktop/lib/aurora/emojiNames.ts: the names emoji packs file
each of Aurora's emojis under, so a pack named by words works as well as one
named by code point.

For every emoji the lyrics can show it collects its Unicode CLDR name and
Teams names (from Microsoft's Fluent Emoji metadata), its GitHub, Slack and
Discord short codes (from GitHub's gemoji) and its Unicode character name,
written the way OmniHub names a pack's pictures (lower case, words joined by
"_"): ❤️ → red_heart, heart, heavy_black_heart. Only names are kept; both
sources are MIT licensed.

Needs git, curl and node 22+:

    python3 scripts/emoji-names.py [--fluent DIR] [--gemoji emoji.json]
"""

import argparse
import glob
import json
import os
import re
import subprocess
import tempfile
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "desktop", "lib", "aurora", "emojiNames.ts")
FLUENT = "https://github.com/microsoft/fluentui-emoji.git"
GEMOJI = "https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json"


def run(args, **kw):
    return subprocess.run(args, check=True, **kw)


def name(text):
    """As media/look.rs names a picture: lower case, words joined by "_"."""
    words = []
    for w in re.split(r"[^0-9A-Za-z]+", text):
        if w:
            words.append(w.lower())
    return "_".join(words)


def key(emoji):
    return "-".join(f"{ord(c):x}" for c in emoji if ord(c) != 0xFE0F)


def emojis(work):
    src = open(os.path.join(ROOT, "src", "desktop", "lib", "aurora", "emoji.ts"), encoding="utf-8").read()
    src = src.replace("import type { EmojiAmount } from '@shared/types';", "type EmojiAmount = 'off' | 'some' | 'more';")
    open(os.path.join(work, "emoji.ts"), "w", encoding="utf-8").write(src)
    open(os.path.join(work, "list.ts"), "w").write("import { ALL_EMOJIS } from './emoji.ts';\nconsole.log(JSON.stringify(ALL_EMOJIS));\n")
    out = run(["node", "--experimental-strip-types", "--no-warnings", os.path.join(work, "list.ts")], capture_output=True, text=True).stdout
    return json.loads(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fluent", help="a fluentui-emoji checkout (only assets/*/metadata.json are read)")
    ap.add_argument("--gemoji", help="gemoji's db/emoji.json")
    a = ap.parse_args()
    work = tempfile.mkdtemp(prefix="omnihub-emoji-names-")
    fluent = a.fluent
    if not fluent:
        fluent = os.path.join(work, "fluent")
        run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", "--depth", "1", FLUENT, fluent])
        run(["git", "-C", fluent, "sparse-checkout", "set", "--no-cone", "/assets/*/metadata.json"])
        run(["git", "-C", fluent, "checkout", "-q"])
    gemoji = a.gemoji
    if not gemoji:
        gemoji = os.path.join(work, "emoji.json")
        run(["curl", "-fsSL", "-o", gemoji, GEMOJI])

    names = {}

    def add(k, n):
        n = name(n)
        if n and n not in names.setdefault(k, []):
            names[k].append(n)

    for f in glob.glob(os.path.join(fluent, "assets", "*", "metadata.json")):
        d = json.load(open(f, encoding="utf-8"))
        k = "-".join(c for c in d.get("unicode", "").split() if c != "fe0f")
        add(k, d.get("cldr", ""))
        for n in d.get("mappedToEmoticons", []) + d.get("glyphAsUtfInEmoticons", []):
            add(k, n)
    for d in json.load(open(gemoji, encoding="utf-8")):
        k = key(d["emoji"])
        add(k, d.get("description", ""))
        for n in d.get("aliases", []):
            add(k, n)

    lines = []
    for e in emojis(work):
        k = key(e)
        found = list(names.get(k, []))
        if len(e.replace("️", "")) == 1:
            try:
                n = name(unicodedata.name(e[0]))
                if n not in found:
                    found.append(n)
            except ValueError:
                pass
        lines.append(f"  {json.dumps(e, ensure_ascii=False)}: {json.dumps(found)},")

    head = (
        "// Generated by scripts/emoji-names.py: the names emoji packs file each of\n"
        "// Aurora's emojis under (CLDR and Teams names from Fluent Emoji's metadata,\n"
        "// GitHub/Slack/Discord short codes from gemoji, both MIT; the Unicode name),\n"
        "// written as OmniHub names a pack's pictures. Do not edit by hand.\n\n"
        "export const EMOJI_NAMES: Record<string, string[]> = {\n"
    )
    open(OUT, "w", encoding="utf-8").write(head + "\n".join(lines) + "\n};\n")
    print(f"{len(lines)} emojis -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
